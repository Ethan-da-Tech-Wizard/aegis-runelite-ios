import Foundation
import CoreGraphics
import MetalKit

/// Context provided to plugins during the Metal hardware rendering pass.
public struct MetalRenderContext {
    public let viewportSize: CGSize
    public let commandBuffer: MTLCommandBuffer?
    public let renderEncoder: MTLRenderCommandEncoder?
    public let gameState: GameState

    /// Initialize render context with frame parameters.
    ///
    /// - Parameters:
    ///   - viewportSize: Screen dimension in points.
    ///   - commandBuffer: Metal command buffer for the active frame.
    ///   - renderEncoder: Metal render command encoder.
    ///   - gameState: Current GameState snapshot.
    public init(
        viewportSize: CGSize,
        commandBuffer: MTLCommandBuffer?,
        renderEncoder: MTLRenderCommandEncoder?,
        gameState: GameState
    ) {
        self.viewportSize = viewportSize
        self.commandBuffer = commandBuffer
        self.renderEncoder = renderEncoder
        self.gameState = gameState
    }
}

/// Primitive draw command generated by plugins to be rendered in Metal.
public enum OverlayDrawCommand {
    case polygon(points: [CGPoint], fillColor: CGColor, strokeColor: CGColor, strokeWidth: CGFloat)
    case text(text: String, position: CGPoint, color: CGColor, fontName: String, fontSize: CGFloat)
    case boundingBox(rect: CGRect, color: CGColor, cornerRadius: CGFloat)
    case icon(imageName: String, rect: CGRect)
}

/// Base protocol that all RuneLite Mobile plugins implement.
public protocol Plugin: AnyObject {
    var id: String { get }
    var name: String { get }
    var description: String { get }
    var isEnabled: Bool { get set }

    /// Called when the plugin is turned ON.
    func startUp()

    /// Called when the plugin is turned OFF.
    func shutDown()

    /// Render overlay elements into the command buffer.
    ///
    /// - Parameter context: The active frame's MetalRenderContext.
    /// - Returns: Array of OverlayDrawCommands to draw this frame.
    func renderOverlay(context: MetalRenderContext) -> [OverlayDrawCommand]
}
